import { DataTypes } from "sequelize";

import { sequelize } from "../config/database.js";

export const BroadcastSchedule =
sequelize.define(
"broadcast_schedules",
{
id:{
type:DataTypes.BIGINT,
autoIncrement:true,
primaryKey:true
},
title:{
type:DataTypes.STRING,
allowNull:false
},
message:{
type:DataTypes.TEXT,
allowNull:false
},
type:{
type:DataTypes.ENUM(
"info",
"offer",
"warning"
),
allowNull:false,
defaultValue:"info"
},
targetAudience:{
type:DataTypes.ENUM(
"female",
"male",
"all"
),
allowNull:false
},
scheduledAtUtc:{
type:DataTypes.DATE,
allowNull:false
},
status:{
type:DataTypes.ENUM(
"pending",
"processing",
"sent",
"cancelled",
"failed"
),
allowNull:false,
defaultValue:"pending"
},
broadcastId:{
type:DataTypes.INTEGER,
allowNull:true
},
createdByAdminId:{
type:DataTypes.STRING(64),
allowNull:true
},
sentAt:{
type:DataTypes.DATE,
allowNull:true
},
errorMessage:{
type:DataTypes.TEXT,
allowNull:true
}
},
{
indexes:[
{
fields:["status","scheduledAtUtc"]
},
{
fields:["targetAudience","status"]
}
]
}
);
