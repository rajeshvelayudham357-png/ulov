export const resolveSupportLanguage = ({ requested, profileLanguages }) => {
  const code = String(requested || "").trim().toLowerCase();

  if (SUPPORT_TRANSLATIONS[code]) {
    return code;
  }

  let list = profileLanguages;

  if (typeof list === "string") {
    try {
      list = JSON.parse(list);
    } catch {
      list = list.split(",");
    }
  }

  const first = Array.isArray(list) ? String(list[0] || "").trim().toLowerCase() : "";
  const match = SUPPORT_LANGUAGES.find((language) => language.profileName === first);
  return match ? match.code : "en";
};

export const createTranslator = (language) => {
  const table = SUPPORT_TRANSLATIONS[language] || SUPPORT_TRANSLATIONS.en;

  return (key, params = {}) => {
    const template = table[key] ?? SUPPORT_TRANSLATIONS.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) =>
      params[name] === undefined || params[name] === null ? "" : String(params[name])
    );
  };
};

